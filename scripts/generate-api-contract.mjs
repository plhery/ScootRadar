import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = process.cwd();
const sourcePath = resolve(root, 'data/scooter-api.schema.json');
const typescriptPath = resolve(root, 'src/generated/scooterApi.ts');
const swiftPaths = [
  resolve(root, 'ios/ScootRadar/Models/ScooterAPIContract.generated.swift'),
];
const checkOnly = process.argv.includes('--check');
// The Android app's build runs this with --kotlin=<directory> (android/core/build.gradle.kts): it then
// writes only the Kotlin models, into its build directory, so they are never stale and the
// website's checks never see them.
const kotlinDirectory = process.argv.find(argument => argument.startsWith('--kotlin='))?.slice('--kotlin='.length);
const schema = JSON.parse(readFileSync(sourcePath, 'utf8'));

function referencedName(reference) {
  const prefix = '#/$defs/';
  if (typeof reference !== 'string' || !reference.startsWith(prefix)) {
    throw new Error(`Unsupported schema reference: ${reference}`);
  }
  return reference.slice(prefix.length);
}

function validateSchemaNode(node, location) {
  if (!node || typeof node !== 'object' || Array.isArray(node)) {
    throw new Error(`Invalid schema node at ${location}`);
  }
  if (node.$ref) {
    const name = referencedName(node.$ref);
    if (!schema.$defs?.[name]) throw new Error(`Unknown schema reference at ${location}: ${name}`);
    return;
  }
  if (node.anyOf) {
    if (!Array.isArray(node.anyOf) || node.anyOf.length < 2) {
      throw new Error(`Invalid anyOf at ${location}`);
    }
    node.anyOf.forEach((item, index) => validateSchemaNode(item, `${location}.anyOf[${index}]`));
    return;
  }
  if (node.enum) {
    if (node.type !== 'string' || !node.enum.every(value => typeof value === 'string')) {
      throw new Error(`Only string enums are supported at ${location}`);
    }
    return;
  }
  if (node.type === 'array') {
    validateSchemaNode(node.items, `${location}.items`);
    return;
  }
  if (node.type === 'object') {
    if (node.properties) {
      for (const [name, property] of Object.entries(node.properties)) {
        validateSchemaNode(property, `${location}.properties.${name}`);
      }
    }
    if (node.additionalProperties && typeof node.additionalProperties === 'object') {
      validateSchemaNode(node.additionalProperties, `${location}.additionalProperties`);
    }
    return;
  }
  if (!['string', 'number', 'integer', 'boolean', 'null'].includes(node.type)) {
    throw new Error(`Unsupported schema type at ${location}: ${node.type}`);
  }
}

function validateSchema() {
  if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema') {
    throw new Error('The API contract must use JSON Schema draft 2020-12');
  }
  if (!schema.title || schema.type !== 'object' || !schema.$defs) {
    throw new Error('The API contract needs a titled object root and definitions');
  }
  validateSchemaNode(schema, schema.title);
}

function nullableType(node, render) {
  if (!node.anyOf) return null;
  const nonNull = node.anyOf.filter(option => option.type !== 'null');
  const nullable = nonNull.length !== node.anyOf.length;
  const rendered = nonNull.map(render).join(' | ');
  return nullable ? `${rendered} | null` : node.anyOf.map(render).join(' | ');
}

function typescriptType(node) {
  if (node.$ref) return referencedName(node.$ref);
  const union = nullableType(node, typescriptType);
  if (union) return union;
  if (node.enum) return node.enum.map(JSON.stringify).join(' | ');
  switch (node.type) {
    case 'string': return 'string';
    case 'number':
    case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${typescriptType(node.items)}[]`;
    case 'object':
      return node.additionalProperties && typeof node.additionalProperties === 'object'
        ? `Record<string, ${typescriptType(node.additionalProperties)}>`
        : 'Record<string, never>';
    default: throw new Error(`Unsupported TypeScript schema type: ${node.type}`);
  }
}

function typescriptDefinition(name, node) {
  if (node.enum) return `export type ${name} = ${typescriptType(node)};`;
  if (node.type !== 'object' || !node.properties) {
    return `export type ${name} = ${typescriptType(node)};`;
  }
  const required = new Set(node.required ?? []);
  const properties = Object.entries(node.properties).map(([property, propertySchema]) => (
    `  ${property}${required.has(property) ? '' : '?'}: ${typescriptType(propertySchema)};`
  ));
  return `export interface ${name} {\n${properties.join('\n')}\n}`;
}

function typescriptContract() {
  const definitions = Object.entries(schema.$defs)
    .map(([name, definition]) => typescriptDefinition(name, definition));
  definitions.push(typescriptDefinition(schema.title, schema));
  return `// Generated by scripts/generate-api-contract.mjs from data/scooter-api.schema.json.\n// Do not edit directly.\n\n${definitions.join('\n\n')}\n`;
}

function swiftDefinitionName(name) {
  const node = name === schema.title ? schema : schema.$defs[name];
  return node?.['x-swift-name'] ?? name;
}

function swiftPropertyName(jsonName, node) {
  return node['x-swift-name'] ?? jsonName.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function swiftType(node) {
  if (node.$ref) return swiftDefinitionName(referencedName(node.$ref));
  if (node.anyOf) {
    const nonNull = node.anyOf.filter(option => option.type !== 'null');
    const nullable = nonNull.length !== node.anyOf.length;
    if (nonNull.length !== 1) throw new Error('Swift generation supports nullable single-type unions only');
    return `${swiftType(nonNull[0])}${nullable ? '?' : ''}`;
  }
  if (node.enum) throw new Error('Inline Swift enums are not supported');
  switch (node.type) {
    case 'string': return 'String';
    case 'number': return 'Double';
    case 'integer': return 'Int';
    case 'boolean': return 'Bool';
    case 'array': return `[${swiftType(node.items)}]`;
    case 'object':
      if (node.additionalProperties && typeof node.additionalProperties === 'object') {
        return `[String: ${swiftType(node.additionalProperties)}]`;
      }
      throw new Error('Anonymous closed Swift objects are not supported');
    default: throw new Error(`Unsupported Swift schema type: ${node.type}`);
  }
}

function swiftCase(value) {
  const identifier = value.replace(/[^a-zA-Z0-9]+(.)/g, (_, letter) => letter.toUpperCase());
  return /^\d/.test(identifier) ? `value${identifier}` : identifier;
}

function swiftDefinition(name, node) {
  const swiftName = swiftDefinitionName(name);
  if (node.enum) {
    const cases = node.enum.map(value => `    case ${swiftCase(value)} = ${JSON.stringify(value)}`);
    return `enum ${swiftName}: String, Decodable, Sendable {\n${cases.join('\n')}\n}`;
  }
  if (node.type !== 'object' || !node.properties) {
    throw new Error(`Swift definitions must be objects or enums: ${name}`);
  }

  const required = new Set(node.required ?? []);
  const properties = [];
  const codingKeys = [];
  let needsCodingKeys = false;
  for (const [jsonName, propertySchema] of Object.entries(node.properties)) {
    const propertyName = swiftPropertyName(jsonName, propertySchema);
    let propertyType = swiftType(propertySchema);
    if (!required.has(jsonName) && !propertyType.endsWith('?')) propertyType += '?';
    properties.push(`    let ${propertyName}: ${propertyType}`);
    if (propertyName !== jsonName) needsCodingKeys = true;
    codingKeys.push(propertyName === jsonName
      ? `        case ${propertyName}`
      : `        case ${propertyName} = ${JSON.stringify(jsonName)}`);
  }
  const codingKeyBlock = !needsCodingKeys
    ? ''
    : `\n\n    private enum CodingKeys: String, CodingKey {\n${codingKeys.join('\n')}\n    }`;
  return `struct ${swiftName}: Decodable, Sendable {\n${properties.join('\n')}${codingKeyBlock}\n}`;
}

function swiftContract() {
  const definitions = Object.entries(schema.$defs)
    .map(([name, definition]) => swiftDefinition(name, definition));
  definitions.push(swiftDefinition(schema.title, schema));
  return `// Generated by scripts/generate-api-contract.mjs from data/scooter-api.schema.json.\n// Do not edit directly.\n\nimport Foundation\n\n${definitions.join('\n\n')}\n`;
}

// The Android app names types, properties and cases the way the iPhone app
// does, in Kotlin's casing: ScooterVehiclePayload.rangeMeters,
// ScooterResponseModePayload.Clusters.
const kotlinKeywords = new Set(['as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if',
  'in', 'interface', 'is', 'null', 'object', 'package', 'return', 'super', 'this', 'throw', 'true', 'try',
  'typealias', 'typeof', 'val', 'var', 'when', 'while']);

function kotlinPropertyName(jsonName, node) {
  const name = swiftPropertyName(jsonName, node);
  if (kotlinKeywords.has(name)) throw new Error(`${name} is a Kotlin keyword; give it an x-swift-name`);
  return name;
}

function kotlinType(node) {
  if (node.$ref) return swiftDefinitionName(referencedName(node.$ref));
  if (node.anyOf) {
    const nonNull = node.anyOf.filter(option => option.type !== 'null');
    const nullable = nonNull.length !== node.anyOf.length;
    if (nonNull.length !== 1) throw new Error('Kotlin generation supports nullable single-type unions only');
    return `${kotlinType(nonNull[0])}${nullable ? '?' : ''}`;
  }
  if (node.enum) throw new Error('Inline Kotlin enums are not supported');
  switch (node.type) {
    case 'string': return 'String';
    case 'number': return 'Double';
    case 'integer': return 'Int';
    case 'boolean': return 'Boolean';
    case 'array': return `List<${kotlinType(node.items)}>`;
    case 'object':
      if (node.additionalProperties && typeof node.additionalProperties === 'object') {
        return `Map<String, ${kotlinType(node.additionalProperties)}>`;
      }
      throw new Error('Anonymous closed Kotlin objects are not supported');
    default: throw new Error(`Unsupported Kotlin schema type: ${node.type}`);
  }
}

function kotlinCase(value) {
  const name = swiftCase(value);
  return name[0].toUpperCase() + name.slice(1);
}

function kotlinDefinition(name, node) {
  const kotlinName = swiftDefinitionName(name);
  if (node.enum) {
    const cases = node.enum.map(value => (
      `    @SerialName(${JSON.stringify(value)}) ${kotlinCase(value)}(${JSON.stringify(value)}),`
    ));
    return [
      '@Serializable',
      `enum class ${kotlinName}(val rawValue: String) {`,
      ...cases,
      '    ;',
      '',
      '    companion object {',
      `        fun fromRawValue(rawValue: String): ${kotlinName}? = entries.firstOrNull { it.rawValue == rawValue }`,
      '    }',
      '}',
    ].join('\n');
  }
  if (node.type !== 'object' || !node.properties || Object.keys(node.properties).length === 0) {
    throw new Error(`Kotlin definitions must be enums or objects with properties: ${name}`);
  }

  // As in Swift, a property that is optional or may be null reads as null
  // whether the key is missing or null.
  const required = new Set(node.required ?? []);
  const properties = Object.entries(node.properties).map(([jsonName, propertySchema]) => {
    const propertyName = kotlinPropertyName(jsonName, propertySchema);
    const serialName = propertyName === jsonName ? '' : `@SerialName(${JSON.stringify(jsonName)}) `;
    let propertyType = kotlinType(propertySchema);
    if (!required.has(jsonName) && !propertyType.endsWith('?')) propertyType += '?';
    const fallback = propertyType.endsWith('?') ? ' = null' : '';
    return `    ${serialName}val ${propertyName}: ${propertyType}${fallback},`;
  });
  return `@Serializable\ndata class ${kotlinName}(\n${properties.join('\n')}\n)`;
}

function kotlinContract() {
  const definitions = Object.entries(schema.$defs)
    .map(([name, definition]) => kotlinDefinition(name, definition));
  definitions.push(kotlinDefinition(schema.title, schema));
  return [
    '// Generated by scripts/generate-api-contract.mjs from data/scooter-api.schema.json.',
    '// Do not edit directly.',
    '',
    'package com.plhery.scootradar.core.generated',
    '',
    'import kotlinx.serialization.SerialName',
    'import kotlinx.serialization.Serializable',
    '',
    `${definitions.join('\n\n')}\n`,
  ].join('\n');
}

function writeOrCheck(path, expected) {
  if (checkOnly) {
    let actual = '';
    try {
      actual = readFileSync(path, 'utf8');
    } catch {}
    if (actual !== expected) {
      console.error(`${path} is out of date. Run npm run generate:api-contract.`);
      process.exitCode = 1;
    }
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, expected);
}

validateSchema();
if (kotlinDirectory) {
  const kotlinPath = resolve(kotlinDirectory, 'com/plhery/scootradar/core/generated/ScooterAPIContract.kt');
  mkdirSync(dirname(kotlinPath), { recursive: true });
  writeFileSync(kotlinPath, kotlinContract());
} else {
  writeOrCheck(typescriptPath, typescriptContract());
  for (const swiftPath of swiftPaths) writeOrCheck(swiftPath, swiftContract());
}
