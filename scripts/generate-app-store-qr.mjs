// Draws the QR code beside the App Store button on the landing page's first
// screen (src/generated/appStoreQr.ts): the app's App Store link with the
// campaign of the code (src/lib/appStore.ts), as one SVG path of its dark
// modules. The page sets it inline, so nothing is fetched to show it.
//
//   npm run generate:app-store-qr
//
// src/lib/appStore.test.ts reads the code back and fails once the link changes
// and this has not been run again.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import { encode } from 'uqr';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/generated/appStoreQr.ts');

// The links import nothing: they compile on their own.
async function load(file) {
  const { code } = await transform(readFileSync(path.join(root, file), 'utf8'), { loader: 'ts', format: 'esm' });
  return import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
}
const { appStoreUrl } = await load('src/lib/appStore.ts');

const url = appStoreUrl('web-qr');
// Level M, which survives a seventh of the code lost. The page draws the quiet zone around it.
const { size, data } = encode(url, { ecc: 'M', border: 0 });

// One rectangle for each run of dark modules along a row.
const runs = data.flatMap((row, y) => {
  const rectangles = [];
  for (let x = 0; x < size; x++) {
    if (!row[x]) continue;
    const start = x;
    while (row[x + 1]) x++;
    const width = x - start + 1;
    rectangles.push(`M${start} ${y}h${width}v1h-${width}z`);
  }
  return rectangles;
});

writeFileSync(out, `// Generated by scripts/generate-app-store-qr.mjs. Do not edit directly.

/** The QR code beside the App Store button: what it reads, its width in modules, and its dark modules as one SVG path. */
export const APP_STORE_QR = {
  url: ${JSON.stringify(url)},
  size: ${size},
  path: ${JSON.stringify(runs.join(''))},
} as const;
`);
console.log(`${path.relative(root, out)}: ${size} × ${size} modules for ${url}`);
